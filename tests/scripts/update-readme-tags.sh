#!/usr/bin/env bash
# Test de update-readme-tags.sh : le rendu du bloc de tags et des versions du
# README. Les README passent en anglais : le marqueur BEGIN et l'en-tete du
# tableau changent, et un README qui porte encore le marqueur francais (rendu
# par v1.4.9 et avant) doit etre migre par son premier rendu, pas refuse --
# sinon chaque depot devrait changer son README dans le meme commit que la
# montee de hardened-ci.
set -euo pipefail
U="$(cd "$(dirname "$0")/../../scripts" && pwd)/update-readme-tags.sh"
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
fail=0
ok() { echo "ok   $*"; }
ko() { echo "FAIL $*"; fail=1; }

NEUF='<!-- BEGIN:tags (generated by CI -- do not edit by hand) -->'
ANCIEN='<!-- BEGIN:tags (genere par la CI -- ne pas editer a la main) -->'
SPEC=jbsky/demo-hardened=1.2.3=1.2.3.4

readme() {  # readme <marqueur> : un README minimal avec un bloc, une prose, des refs
  cat > "$T/README.md" <<EOF
# demo
Demo <!--v:demo-hardened-->1.2.2<!--/v--> en prose.
$1
| Image | Version amont | Tag immuable a epingler |
|-------|---------------|-------------------------|
| \`jbsky/demo-hardened\` | \`1.2.2\` | \`1.2.2.9\` |
<!-- END:tags -->
docker run jbsky/demo-hardened:1.2.2.9 ghcr.io/jbsky/demo-hardened:latest
EOF
}
rend() { ( cd "$T" && "$U" "$@" ) > "$T/sortie.txt" 2>&1; }

# --- 1. marqueur francais : accepte, remplace, en-tete anglais ----------
readme "$ANCIEN"
# SC2016 : les accents graves sont du Markdown litteral, pas une substitution.
# shellcheck disable=SC2016
if rend "$SPEC" \
   && grep -qxF "$NEUF" "$T/README.md" \
   && ! grep -qF "$ANCIEN" "$T/README.md" \
   && grep -qxF '| Image | Upstream version | Immutable tag to pin |' "$T/README.md" \
   && grep -qF '| `jbsky/demo-hardened` | `1.2.3` | `1.2.3.4` |' "$T/README.md"; then
  ok "marqueur francais migre : marqueur et en-tete anglais, ligne a jour"
else ko "migration du marqueur francais"; cat "$T/sortie.txt"; cat "$T/README.md"; fi

# --- 2. marqueur anglais : rendu idempotent (--check vert) ---------------
if rend --check "$SPEC"; then
  ok "second rendu identique (--check)"
else ko "rendu non idempotent"; cat "$T/sortie.txt"; fi

# --- 3. prose et references : version et tag immuable, :latest intact ---
if grep -qF '<!--v:demo-hardened-->1.2.3<!--/v-->' "$T/README.md" \
   && grep -qF 'docker run jbsky/demo-hardened:1.2.3.4 ' "$T/README.md" \
   && grep -qF 'ghcr.io/jbsky/demo-hardened:latest' "$T/README.md"; then
  ok "prose et references rendues, :latest laisse flottant"
else ko "prose ou references"; cat "$T/README.md"; fi

# --- 4. garde : version perimee hors zone generee -----------------------
readme "$NEUF"; echo "Toujours en 1.2.1 ici." >> "$T/README.md"
if ! rend "$SPEC" && grep -q '1.2.1' "$T/sortie.txt"; then
  ok "version perimee en prose : echec qui la nomme"
else ko "la garde laisse passer 1.2.1"; cat "$T/sortie.txt"; fi
readme "$NEUF"; echo "Corrige depuis la 1.2.1. <!-- version-fixe -->" >> "$T/README.md"
if rend "$SPEC"; then
  ok "ligne exemptee par <!-- version-fixe -->"
else ko "exemption version-fixe"; cat "$T/sortie.txt"; fi

# --- 5. aucun marqueur : echec net, README intact -----------------------
printf '# sans bloc\n' > "$T/README.md"
if ! rend "$SPEC" && [ "$(cat "$T/README.md")" = "# sans bloc" ]; then
  ok "sans marqueur : echec, README intact"
else ko "sans marqueur"; cat "$T/sortie.txt"; fi

exit "$fail"
